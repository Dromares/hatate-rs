#[test]
fn urljoin_agrees_with_python() {
    let mut bad = Vec::new();
    for (base, reference, want) in JOINS {
        let got = urljoin(base, reference);
        if got != *want {
            bad.push(format!(
                "urljoin({base:?}, {reference:?}): want {want:?}, got {got:?}"
            ));
        }
    }
    assert!(
        bad.is_empty(),
        "{} of {} differ:\n{}",
        bad.len(),
        JOINS.len(),
        bad.join("\n")
    );
}

